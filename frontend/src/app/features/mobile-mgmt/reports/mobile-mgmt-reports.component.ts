export class MobileMgmtReportsComponent implements OnInit {
  items: MobileMgmtReport[] = [];
  total = 0;
  offset = 0;
  limit = 10;
  searchQuery = '';
  categoryFilter = '';

  isModalOpen = false;
  isEditing = false;
  currentItem: Partial<MobileMgmtReport> = {};

  constructor(private service: MobileMgmtService) {}

  ngOnInit(): void {
    this.loadData();
  }

  loadData(): void {
    this.service.getReports({
      limit: this.limit,
      offset: this.offset,
      search: this.searchQuery || undefined,
      category: this.categoryFilter || undefined
    }).subscribe((res: any) => {
      this.items = res.items;
      this.total = res.total;
    });
  }

  prevPage(): void {
    if (this.offset > 0) {
      this.offset = Math.max(0, this.offset - this.limit);
      this.loadData();
    }
  }

  nextPage(): void {
    if (this.offset + this.limit < this.total) {
      this.offset += this.limit;
      this.loadData();
    }
  }

  openAddModal(): void {
    this.isEditing = false;
    this.currentItem = {
      title: '',
      category: 'Executive Digest',
      period: 'Monthly 2026',
      file_format: 'PDF',
      file_size: '1.8 MB',
      download_url: '/static/reports/demo.pdf',
      generated_by: 'CFO Office'
    };
    this.isModalOpen = true;
  }

  openEditModal(item: MobileMgmtReport): void {
    this.isEditing = true;
    this.currentItem = { ...item };
    this.isModalOpen = true;
  }

  saveItem(): void {
    if (this.isEditing && this.currentItem.id) {
      this.service.updateReport(this.currentItem.id, this.currentItem).subscribe(() => {
        this.isModalOpen = false;
        this.loadData();
      });
    } else {
      this.service.createReport(this.currentItem).subscribe(() => {
        this.isModalOpen = false;
        this.loadData();
      });
    }
  }

  deleteItem(id: number | undefined): void {
    if (!id) return;
    if (confirm('Are you sure you want to delete this report?')) {
      this.service.deleteReport(id).subscribe(() => {
        this.loadData();
      });
    }
  }

  downloadReport(item: MobileMgmtReport): void {
    item.download_count = (item.download_count || 0) + 1;
    if (item.id) {
      this.service.updateReport(item.id, { download_count: item.download_count }).subscribe();
    }
    alert(`Downloading ${item.title} (${item.file_format})...`);
  }
}
